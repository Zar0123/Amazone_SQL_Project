/*
12. Product Profit Margin
Calculate the profit margin for each product (difference between price and cost of goods sold).
Challenge: Rank products by their profit margin, showing highest to lowest.
*/
-- o - oi -prod
-- group pid 
-- SUM(total_sale - cogs * qty) AS profit
-- profit_margin (profit/SUM(total_sale) * 100)
SELECT
	product_id,
	product_name,
	profit_margin,
	DENSE_RANK() OVER(ORDER BY profit_margin DESC) AS product_ranking
FROM
(SELECT 
	p.product_id,
	p.product_name,
	ROUND(SUM(oi.total_sale - (p.cogs * oi.quantity))::numeric, 2) AS profit,
	ROUND(SUM(oi.total_sale - (p.cogs * oi.quantity))::numeric, 2)/SUM(oi.total_sale)*100 AS profit_margin
FROM order_items AS oi
INNER JOIN products AS p
	ON p.product_id = oi.product_id
GROUP BY 1, 2
) AS profit_table
;


