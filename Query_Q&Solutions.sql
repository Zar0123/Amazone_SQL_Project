/*
2. Revenue by Category
Calculate total revenue generated by each product category.
Challenge: Include the percentage contribution of each category to total revenue.
*/
-- Solution
-- Category_id, cat_name, total_revenue, total contribution
-- oi -- products -- category
-- group by cat id and name sum total(oi)

SELECT 
	p.category_id,
	ca.category_name,
	ROUND(SUM(oi.total_sale)::numeric, 2) AS total_revenue,
	CONCAT(ROUND((SUM(oi.total_sale)/ 
		(SELECT SUM(total_sale) FROM order_items) * 100)::numeric, 2),'%')
		AS contribution
FROM order_items oi
INNER JOIN products p
	ON p.product_id = oi.product_id
LEFT JOIN category ca
	ON p.category_id = ca.category_id
GROUP BY 1, 2
ORDER BY 3 DESC
;

/*
3. Average Order Value (AOV)
Compute the average order value for each customer.
Challenge: Include only customers with more than 5 orders.
*/
-- Solution
-- o -- oi - cu
-- group by cu_id and cu_name SUM(Total Sale)/no orders
SELECT
	c.customer_id,
	CONCAT(c.first_name,' ',c.last_name) AS customer_name,
	SUM(oi.total_sale)/COUNT(o.order_id) AS avg_order_value,
	COUNT(o.order_id) AS total_orders
FROM orders AS o
INNER JOIN customers AS c
	ON c.customer_id = o.customer_id
INNER JOIN order_items AS oi
	ON oi.order_id = o.order_id
GROUP BY 1,2
HAVING COUNT(o.order_id) > 5
;

/*
4. Monthly Sales Trend
Query monthly total sales over the past year. 
Challenge: Display the sales trend, grouping by month, return current_month sale, last month sale!
*/
-- last 1 year data
-- each month -- their sales and their prev month sale
-- window leg

SELECT
	year,
	month,
	overall_total_sales,
	LAG(overall_total_sales, 1) OVER(ORDER BY year, month) AS last_month_sale
FROM
(SELECT 
	EXTRACT(MONTH FROM order_date) AS month,
	EXTRACT(YEAR FROM order_date) AS year,
	ROUND(
		SUM(oi.total_sale)::numeric
		, 3) AS overall_total_sales
FROM orders as o
JOIN order_items oi
	ON o.order_id = oi.order_id
WHERE order_date >= CURRENT_DATE - INTERVAL '3 year'
GROUP BY 1, 2
ORDER BY year, month
) AS query_1
;

